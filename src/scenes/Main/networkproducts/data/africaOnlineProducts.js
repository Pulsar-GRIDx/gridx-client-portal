// Structured Africa Online Namibia product catalogue. Pure data — no React/JSX
// here on purpose, so pricing can be updated by anyone comfortable editing a
// plain object, and so this file stays reusable outside the card component
// (e.g. a future comparison export, or a backend-driven catalogue later).
//
// SOURCING
// Every product, price and feature below was read off Africa Online's own
// product pages (linked per-product in `href`, and listed in `productSources`
// at the bottom) in August 2026. Nothing here is inferred or filled in from a
// competitor: where Africa Online publishes no price, `price` is null and the
// card falls back to a "Request quote" / "Contact sales" CTA rather than
// showing a number we made up.
//
// STRUCTURE
// Africa Online groups 12 products under 3 categories. Several of those pages
// cover more than one distinctly-named plan family (the Jet page covers Jet
// Home, Jet Business and Jet Express; the Fibre page covers NawaFi, OptiFi and
// Dedicated Fibre; the VSAT page covers Epic Home, Business and Unlimited).
// Those are split into their own cards here because Africa Online names and
// prices them separately — the split follows their catalogue, it does not
// invent tiers.
//
// VAT
// Africa Online quotes ex-VAT on the Jet, LTE, Microsoft 365, firewall, email
// and domain pages. `exVat: true` drives the "ex VAT" suffix on the card so the
// figure is never mistaken for an inc-VAT retail price.

